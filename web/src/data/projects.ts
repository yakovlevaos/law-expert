export type Project = {
  slug: string;
  title: string;
  period: string;
  coverage: string;
  place: string;
  funding: string;
  partners: string[];
  description: string;
  /**
   * Media file names under /images. A bare name is a `.jpeg` image
   * (`"mirror1"` → `/images/mirror1.jpeg`); a name carrying an extension is
   * used verbatim, and `.mp4` entries render as video.
   */
  media: string[];
};

export type ProjectMedia = {
  src: string;
  kind: "image" | "video";
};

const VIDEO_EXTENSIONS = new Set(["mp4", "webm", "ogg"]);

/** Resolves a `media` entry to a runtime URL plus the element it needs. */
export const resolveMedia = (entry: string): ProjectMedia => {
  const dot = entry.lastIndexOf(".");
  const extension = dot === -1 ? "" : entry.slice(dot + 1).toLowerCase();

  if (!extension) return { src: `/images/${entry}.jpeg`, kind: "image" };
  return {
    src: `/images/${entry}`,
    kind: VIDEO_EXTENSIONS.has(extension) ? "video" : "image",
  };
};

